CREATE TABLE CLIENT_NOTIFICATION_OUTBOX (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_ID           VARCHAR2(50) NOT NULL,
    SHIPMENT_ID         NUMBER NOT NULL,
    RPT_ENVIO_RUTA_ID   NUMBER,
    EVENT_CODE          VARCHAR2(50),
    SUB_EVENT_CODE      VARCHAR2(50),
    HOMOLOGATION_ID     NUMBER,
    EMISION             CHAR(2),
    REMITO              NUMBER,
    STATUS              VARCHAR2(20) NOT NULL,
    ATTEMPT_COUNT       NUMBER DEFAULT 0 NOT NULL,
    LAST_ERROR_CODE     VARCHAR2(50),
    LAST_ERROR_MESSAGE  VARCHAR2(500),
    LAST_HTTP_STATUS    NUMBER,
    LAST_RESPONSE_BODY  CLOB,
    PAYLOAD_SNAPSHOT    CLOB,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP,
    PROCESSED_AT        TIMESTAMP
);

CREATE INDEX IDX_CN_OUTBOX_STATUS_RETRY
    ON CLIENT_NOTIFICATION_OUTBOX (STATUS);

CREATE INDEX IDX_CN_OUTBOX_SHIPMENT_ORDER
    ON CLIENT_NOTIFICATION_OUTBOX (SHIPMENT_ID, CREATED_AT);

CREATE INDEX IDX_CN_OUTBOX_CLIENT
    ON CLIENT_NOTIFICATION_OUTBOX (CLIENT_ID);

CREATE INDEX IDX_CN_OUTBOX_RPT_ENVIO
    ON CLIENT_NOTIFICATION_OUTBOX (RPT_ENVIO_RUTA_ID);

CREATE INDEX IDX_CN_OUTBOX_ATTEMPTS
    ON CLIENT_NOTIFICATION_OUTBOX (ATTEMPT_COUNT);

CREATE TABLE CLIENT_NOTIFICATION_ATTEMPT (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OUTBOX_ID           NUMBER NOT NULL,
    ATTEMPT_NUMBER      NUMBER NOT NULL,
    REQUEST_PAYLOAD     CLOB,
    RESPONSE_STATUS     NUMBER,
    RESPONSE_BODY       CLOB,
    ERROR_TYPE          VARCHAR2(50),
    ERROR_MESSAGE       VARCHAR2(500),
    ATTEMPTED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CN_ATTEMPT_OUTBOX
        FOREIGN KEY (OUTBOX_ID)
        REFERENCES CLIENT_NOTIFICATION_OUTBOX (ID)
);

CREATE INDEX IDX_CN_ATTEMPT_OUTBOX
    ON CLIENT_NOTIFICATION_ATTEMPT (OUTBOX_ID);

CREATE INDEX IDX_CN_ATTEMPT_OUTBOX_NUM
    ON CLIENT_NOTIFICATION_ATTEMPT (OUTBOX_ID, ATTEMPT_NUMBER);

CREATE INDEX IDX_CN_ATTEMPT_DATE
    ON CLIENT_NOTIFICATION_ATTEMPT (ATTEMPTED_AT);

CREATE INDEX IDX_OUTBOX_READY
    ON CLIENT_NOTIFICATION_OUTBOX (STATUS, CREATED_AT);
